<?php
/**
 * Chore Slayer — web installer / setup wizard.
 *
 * Visit this file in a browser after uploading the app to cPanel. It will
 * check requirements, test your MySQL details, write config.php, create the
 * database tables, and set your parent PIN — then lock itself.
 *
 * Delete this file when you're done (the last screen offers a one-click button).
 */

define('CHORE_APP', true);

$APP_DIR   = __DIR__;
$CONFIG    = $APP_DIR . '/config.php';
$LOCK      = $APP_DIR . '/installed.lock';
$LIB       = $APP_DIR . '/lib';
$PHP_MIN   = '7.4.0';

$errors  = [];
$notice  = '';
$step    = $_GET['step'] ?? 'welcome';
$action  = $_POST['action'] ?? '';

// --------------------------------------------------------------------------
// tiny helpers
// --------------------------------------------------------------------------
function e($s) { return htmlspecialchars((string) $s, ENT_QUOTES, 'UTF-8'); }

function redirect($to) { header('Location: ' . $to); exit; }

function requirements_list($APP_DIR, $PHP_MIN) {
    return [
        [
            'label' => 'PHP ' . $PHP_MIN . ' or newer',
            'ok'    => version_compare(PHP_VERSION, $PHP_MIN, '>='),
            'fix'   => 'You have PHP ' . PHP_VERSION . '. In cPanel open “Select PHP Version” and choose 8.0+.',
        ],
        [
            'label' => 'MySQL driver (pdo_mysql)',
            'ok'    => extension_loaded('pdo_mysql'),
            'fix'   => 'In cPanel “Select PHP Version” → Extensions, tick “pdo_mysql”.',
        ],
        [
            'label' => 'JSON support',
            'ok'    => function_exists('json_encode'),
            'fix'   => 'Enable the “json” extension in cPanel “Select PHP Version”.',
        ],
        [
            'label' => 'App folder is writable',
            'ok'    => is_writable($APP_DIR),
            'fix'   => 'Not required — if this stays red, the installer will show you config.php to create by hand.',
            'soft'  => true,
        ],
    ];
}

function build_config_php(array $cfg) {
    return "<?php\n"
        . "// Generated by the Chore Slayer installer. Safe to edit by hand.\n"
        . "// Holds your database password — never share this file.\n"
        . "return " . var_export($cfg, true) . ";\n";
}

/** Is the app already fully installed? (lock file, or config + a parent PIN set) */
function already_installed($CONFIG, $LOCK) {
    if (file_exists($LOCK)) {
        return true;
    }
    if (!file_exists($CONFIG)) {
        return false;
    }
    $cfg = @include $CONFIG;
    if (!is_array($cfg) || empty($cfg['db_name'])) {
        return false;
    }
    try {
        $dsn = sprintf('mysql:host=%s;dbname=%s;charset=%s',
            $cfg['db_host'] ?? 'localhost', $cfg['db_name'], $cfg['db_charset'] ?? 'utf8mb4');
        $pdo = new PDO($dsn, $cfg['db_user'] ?? '', $cfg['db_pass'] ?? '',
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_TIMEOUT => 4]);
        // Installed once the multi-family schema is present.
        $pdo->query('SELECT 1 FROM families LIMIT 1');
        return true;
    } catch (Throwable $ex) {
        return false;
    }
}

$installed = already_installed($CONFIG, $LOCK);

// --------------------------------------------------------------------------
// handle actions (before any HTML output)
// --------------------------------------------------------------------------

// Allow deleting the installer even once installed.
if ($action === 'delete_self') {
    $gone = @unlink(__FILE__);
    @unlink($LOCK); // lock no longer needed once installer is gone
    if ($gone) {
        // File is deleted; send the user to the app.
        redirect('index.php');
    }
    $notice = 'Could not delete the installer automatically. Please delete install.php in cPanel File Manager.';
    $step = 'done';
}

// Block fresh-install actions if already installed.
if ($installed && in_array($action, ['save_db', 'finalize'], true)) {
    $step = 'installed';
}

// Step: save database details + create tables.
elseif ($action === 'save_db') {
    $vals = [
        'db_host'  => trim($_POST['db_host'] ?? 'localhost'),
        'db_name'  => trim($_POST['db_name'] ?? ''),
        'db_user'  => trim($_POST['db_user'] ?? ''),
        'db_pass'  => (string) ($_POST['db_pass'] ?? ''),
        'timezone' => trim($_POST['timezone'] ?? 'America/Chicago'),
    ];
    if ($vals['db_name'] === '' || $vals['db_user'] === '') {
        $errors[] = 'Database name and username are required.';
    }
    if (!in_array($vals['timezone'], DateTimeZone::listIdentifiers(), true)) {
        $errors[] = 'That timezone was not recognized. Pick one from the list.';
    }
    if (!$errors) {
        try {
            $dsn = sprintf('mysql:host=%s;dbname=%s;charset=utf8mb4', $vals['db_host'], $vals['db_name']);
            $pdo = new PDO($dsn, $vals['db_user'], $vals['db_pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);

            $cfg = [
                'db_host'      => $vals['db_host'],
                'db_name'      => $vals['db_name'],
                'db_user'      => $vals['db_user'],
                'db_pass'      => $vals['db_pass'],
                'db_charset'   => 'utf8mb4',
                'session_days' => 30,
                'timezone'     => $vals['timezone'],
                'debug'        => false,
            ];
            $configText = build_config_php($cfg);

            $wrote = @file_put_contents($CONFIG, $configText);
            if ($wrote === false) {
                // Folder not writable — fall through to manual instructions.
                $errors[] = '__MANUAL__';
                $GLOBALS['manual_config'] = $configText;
            } else {
                // Reuse the app's own schema installer so they never drift.
                require_once $LIB . '/helpers.php';
                require_once $LIB . '/db.php';
                require_once $LIB . '/auth.php';
                install_schema();
                @file_put_contents($LOCK, 'installed ' . gmdate('c'));
                redirect('install.php?step=done');
            }
        } catch (PDOException $ex) {
            $errors[] = 'Could not connect / set up the database: ' . $ex->getMessage();
        } catch (Throwable $ex) {
            $errors[] = 'Setup error: ' . $ex->getMessage();
        }
    }
    if ($errors) {
        $step = 'database';
        $GLOBALS['db_vals'] = $vals;
    }
}

// Step: finalize — used by the manual-config path to create tables + lock.
// Families/PINs are created by parents in the app or web (signup), not here.
elseif ($action === 'finalize') {
    if (!file_exists($CONFIG)) {
        redirect('install.php?step=database');
    }
    try {
        require_once $LIB . '/helpers.php';
        require_once $LIB . '/db.php';
        require_once $LIB . '/auth.php';
        install_schema();
        @file_put_contents($LOCK, 'installed ' . gmdate('c'));
        redirect('install.php?step=done');
    } catch (Throwable $ex) {
        $errors[] = 'Could not finish setup: ' . $ex->getMessage();
        $step = 'database';
    }
}

// If they navigate to a fresh step while already installed, show the notice.
if ($installed && in_array($step, ['welcome', 'database'], true) && $action === '') {
    $step = 'installed';
}

// --------------------------------------------------------------------------
// render
// --------------------------------------------------------------------------
$STEPS = ['welcome' => 'Welcome', 'database' => 'Database', 'done' => 'Finish'];
$activeIndex = array_search($step === 'installed' ? 'done' : $step, array_keys($STEPS), true);
if ($activeIndex === false) { $activeIndex = 0; }
?><!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>Install — Chore Slayer</title>
    <link rel="stylesheet" href="assets/styles.css?v=1">
    <style>
        .install-wrap { max-width: 640px; margin: 0 auto; }
        .steps { display: flex; gap: 8px; list-style: none; padding: 0; margin: 0 0 22px; flex-wrap: wrap; }
        .steps li { flex: 1; min-width: 110px; text-align: center; padding: 10px 6px; border-radius: 10px;
            background: var(--surface-alt); color: var(--ink-soft); font-weight: 600; font-size: .9rem; border: 1px solid var(--border); }
        .steps li.active { background: var(--brand); color: #fff; border-color: var(--brand); }
        .steps li.done { background: #eafaf1; color: var(--good-dark); border-color: var(--good); }
        .req { list-style: none; padding: 0; margin: 0 0 18px; display: grid; gap: 10px; }
        .req li { display: flex; gap: 12px; align-items: flex-start; padding: 12px 14px; border: 1px solid var(--border);
            border-radius: 12px; background: var(--surface); }
        .req .icon { font-size: 1.3rem; line-height: 1.4; }
        .req .ok-yes { color: var(--good-dark); }
        .req .ok-no { color: var(--bad); }
        .req .fix { color: var(--ink-soft); font-size: .9rem; margin-top: 2px; }
        .alert { padding: 14px 16px; border-radius: 12px; margin-bottom: 16px; }
        .alert--error { background: #fbe7e3; border: 1px solid var(--bad); color: #8a2d1c; }
        .alert--ok { background: #eafaf1; border: 1px solid var(--good); color: var(--good-dark); }
        .alert ul { margin: 6px 0 0; padding-left: 20px; }
        code.path { background: var(--surface-alt); padding: 2px 6px; border-radius: 6px; }
    </style>
</head>
<body>
    <header class="app-header" role="banner">
        <div class="app-header__inner">
            <span class="app-logo" aria-hidden="true">🛠️</span>
            <h1 class="app-title">Chore Slayer — Installer</h1>
        </div>
    </header>

    <main id="main" tabindex="-1">
        <div class="install-wrap">
            <ol class="steps" aria-label="Installation steps">
                <?php $i = 0; foreach ($STEPS as $key => $label): ?>
                    <li class="<?= $i === $activeIndex ? 'active' : ($i < $activeIndex ? 'done' : '') ?>">
                        <?= ($i < $activeIndex ? '✓ ' : '') . e($label) ?><?php if ($i === $activeIndex): ?> <span class="sr-only">(current step)</span><?php endif; ?>
                    </li>
                <?php $i++; endforeach; ?>
            </ol>

            <?php if ($notice): ?>
                <div class="alert alert--ok"><?= e($notice) ?></div>
            <?php endif; ?>

            <?php if ($errors && $errors !== ['__MANUAL__']): ?>
                <div class="alert alert--error">
                    <strong>Please fix the following:</strong>
                    <ul><?php foreach ($errors as $err) { if ($err !== '__MANUAL__') echo '<li>' . e($err) . '</li>'; } ?></ul>
                </div>
            <?php endif; ?>

            <?php
            // ============================ WELCOME / REQUIREMENTS ============================
            if ($step === 'welcome'):
                $reqs = requirements_list($APP_DIR, $PHP_MIN);
                $blocking = false;
                foreach ($reqs as $r) { if (!$r['ok'] && empty($r['soft'])) { $blocking = true; } }
            ?>
                <div class="card">
                    <h2 class="panel-title">Welcome 👋</h2>
                    <p class="panel-sub">This wizard will set up the Chore Slayer on your server. First, a quick check of your hosting.</p>
                    <ul class="req">
                        <?php foreach ($reqs as $r): ?>
                            <li>
                                <span class="icon <?= $r['ok'] ? 'ok-yes' : 'ok-no' ?>" aria-hidden="true"><?= $r['ok'] ? '✅' : '⛔' ?></span>
                                <div>
                                    <strong><?= e($r['label']) ?></strong>
                                    <span class="sr-only"><?= $r['ok'] ? ' — OK' : ' — not met' ?></span>
                                    <?php if (!$r['ok']): ?><div class="fix"><?= e($r['fix']) ?></div><?php endif; ?>
                                </div>
                            </li>
                        <?php endforeach; ?>
                    </ul>
                    <?php if ($blocking): ?>
                        <div class="alert alert--error">Some required items above need attention before you can continue. Fix them in cPanel, then reload this page.</div>
                        <a class="btn btn--ghost" href="install.php">Re-check</a>
                    <?php else: ?>
                        <a class="btn btn--lg" href="install.php?step=database">Start setup →</a>
                    <?php endif; ?>
                </div>

            <?php
            // ============================ MANUAL CONFIG (folder not writable) ============================
            elseif ($step === 'database' && $errors === ['__MANUAL__'] || isset($GLOBALS['manual_config'])):
                $manual = $GLOBALS['manual_config'] ?? '';
            ?>
                <div class="card">
                    <h2 class="panel-title">Create config.php by hand</h2>
                    <p class="panel-sub">Your app folder isn’t writable, so the installer can’t create the file for you. That’s fine — copy the text below into a new file called <code class="path">config.php</code> in the same folder (cPanel File Manager → <em>+ File</em>), then continue.</p>
                    <div class="field">
                        <label for="manual">config.php contents</label>
                        <textarea id="manual" rows="14" readonly onclick="this.select()"><?= e($manual) ?></textarea>
                    </div>
                    <a class="btn" href="install.php?action=finalize">I’ve created it — continue →</a>
                    <a class="btn btn--ghost" href="install.php?step=database">Back</a>
                </div>

            <?php
            // ============================ DATABASE ============================
            elseif ($step === 'database'):
                $v = $GLOBALS['db_vals'] ?? ['db_host' => 'localhost', 'db_name' => '', 'db_user' => '', 'db_pass' => '', 'timezone' => 'America/Chicago'];
            ?>
                <div class="card">
                    <h2 class="panel-title">Database connection</h2>
                    <p class="panel-sub">In cPanel → <strong>MySQL® Databases</strong>, create a database and a user, then add the user to the database with <strong>ALL PRIVILEGES</strong>. Enter those details here.</p>
                    <form method="post" action="install.php?step=database">
                        <input type="hidden" name="action" value="save_db">
                        <div class="row">
                            <div class="field"><label for="db_host">Database host</label>
                                <input type="text" id="db_host" name="db_host" value="<?= e($v['db_host']) ?>">
                                <div class="help">Almost always <code class="path">localhost</code> on cPanel.</div>
                            </div>
                            <div class="field"><label for="db_name">Database name</label>
                                <input type="text" id="db_name" name="db_name" value="<?= e($v['db_name']) ?>" placeholder="youracct_chores" required>
                            </div>
                        </div>
                        <div class="row">
                            <div class="field"><label for="db_user">Database user</label>
                                <input type="text" id="db_user" name="db_user" value="<?= e($v['db_user']) ?>" placeholder="youracct_choreapp" required>
                            </div>
                            <div class="field"><label for="db_pass">Database password</label>
                                <input type="password" id="db_pass" name="db_pass" value="<?= e($v['db_pass']) ?>">
                            </div>
                        </div>
                        <div class="field"><label for="timezone">Timezone</label>
                            <select id="timezone" name="timezone">
                                <?php foreach (DateTimeZone::listIdentifiers() as $tz): ?>
                                    <option value="<?= e($tz) ?>" <?= $tz === $v['timezone'] ? 'selected' : '' ?>><?= e($tz) ?></option>
                                <?php endforeach; ?>
                            </select>
                            <div class="help">Used to decide what “today” is for check-offs and reports.</div>
                        </div>
                        <button class="btn btn--lg" type="submit">Test &amp; continue →</button>
                    </form>
                </div>

            <?php
            // ============================ DONE ============================
            elseif ($step === 'done'):
            ?>
                <div class="card">
                    <h2 class="panel-title">All set! 🎉</h2>
                    <p class="panel-sub">The Chore Slayer is installed. Open the app to <strong>create your family</strong> (pick a parent PIN) — you’ll get a Family Code for adding more devices or signing in on the web.</p>
                    <p><strong>One last step for safety:</strong> remove this installer so it can’t be run again.</p>
                    <form method="post" action="install.php" style="display:inline">
                        <input type="hidden" name="action" value="delete_self">
                        <button class="btn btn--danger" type="submit">🗑️ Delete installer &amp; open the app</button>
                    </form>
                    <a class="btn btn--ghost" href="index.php">Skip — open the app</a>
                    <p class="help" style="margin-top:14px">If the delete button doesn’t work (some hosts block it), just delete <code class="path">install.php</code> and <code class="path">installed.lock</code> in cPanel File Manager.</p>
                </div>

            <?php
            // ============================ ALREADY INSTALLED ============================
            else: // 'installed'
            ?>
                <div class="card">
                    <h2 class="panel-title">Already installed ✅</h2>
                    <p class="panel-sub">This app is already set up, so the installer is locked to protect your data.</p>
                    <a class="btn" href="index.php">Open the app</a>
                    <form method="post" action="install.php" style="display:inline">
                        <input type="hidden" name="action" value="delete_self">
                        <button class="btn btn--danger" type="submit">🗑️ Delete this installer</button>
                    </form>
                    <p class="help" style="margin-top:14px">To re-run setup intentionally, delete <code class="path">installed.lock</code> (and <code class="path">config.php</code> to start fully fresh) in cPanel.</p>
                </div>
            <?php endif; ?>
        </div>
    </main>

